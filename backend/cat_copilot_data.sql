-- CAT Co-Pilot synthetic data: schema + data (PostgreSQL)
-- Load order: operators, machines, telemetry_log, task_duration_log

DROP TABLE IF EXISTS task_duration_log;
DROP TABLE IF EXISTS telemetry_log;
DROP TABLE IF EXISTS operators;
DROP TABLE IF EXISTS machines;

CREATE TABLE operators (
    operator_id             VARCHAR(10) PRIMARY KEY,
    name                    VARCHAR(50) NOT NULL,
    skill_level             VARCHAR(20) NOT NULL,
    years_experience        INTEGER NOT NULL,
    shift                   VARCHAR(10) NOT NULL,
    license_type            VARCHAR(40) NOT NULL,
    training_completion_pct NUMERIC(5,1) NOT NULL,
    hire_date               DATE NOT NULL,
    safety_violations_ytd   INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE machines (
    machine_id            VARCHAR(10) PRIMARY KEY,
    machine_type          VARCHAR(30) NOT NULL,
    model                 VARCHAR(20) NOT NULL,
    machine_age_yrs       INTEGER NOT NULL,
    purchase_date         DATE NOT NULL,
    last_maintenance_date DATE NOT NULL,
    lifetime_engine_hours INTEGER NOT NULL,
    fuel_tank_capacity_l  INTEGER NOT NULL,
    status                VARCHAR(20) NOT NULL
);

CREATE TABLE telemetry_log (
    id                      SERIAL PRIMARY KEY,
    ts                      TIMESTAMP NOT NULL,
    machine_id              VARCHAR(10) NOT NULL REFERENCES machines(machine_id),
    operator_id             VARCHAR(10) NOT NULL REFERENCES operators(operator_id),
    engine_hours            NUMERIC(4,1) NOT NULL,
    fuel_used_l             NUMERIC(6,1) NOT NULL,
    load_cycles             INTEGER NOT NULL,
    idling_time_min         NUMERIC(5,1) NOT NULL,
    seatbelt_status         VARCHAR(20) NOT NULL,
    safety_alert_triggered  BOOLEAN NOT NULL
);

CREATE TABLE task_duration_log (
    task_id             VARCHAR(10) PRIMARY KEY,
    task_type           VARCHAR(50) NOT NULL,
    weather              VARCHAR(20) NOT NULL,
    operator_id         VARCHAR(10) NOT NULL REFERENCES operators(operator_id),
    machine_id          VARCHAR(10) NOT NULL REFERENCES machines(machine_id),
    operator_skill      VARCHAR(20) NOT NULL,
    machine_age_yrs     INTEGER NOT NULL,
    estimated_time_min  INTEGER NOT NULL,
    actual_time_min     INTEGER NOT NULL
);

CREATE INDEX idx_telemetry_machine ON telemetry_log(machine_id);
CREATE INDEX idx_telemetry_operator ON telemetry_log(operator_id);
CREATE INDEX idx_telemetry_ts ON telemetry_log(ts);
CREATE INDEX idx_task_operator ON task_duration_log(operator_id);
CREATE INDEX idx_task_machine ON task_duration_log(machine_id);

